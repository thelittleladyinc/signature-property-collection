#!/usr/bin/env python3
"""Export the site's map data as Mapbox-ready GeoJSON, and assemble the
brand-styled Mapbox GL preview page.

2026-08-20 (Christine: "it allows me to upload the json - can you make it
gorgeous?!"). Mapbox Studio accepts GeoJSON uploads as datasets/tilesets,
so this writes her real map data -- the same sources the Leaflet county
map draws from -- in that format, plus a self-contained preview page
(mapbox/preview.html) that shows the whole thing styled to the brand.

Reads (never hand-maintains -- same anti-drift rule as county-search.json):
  - site/assets/data/noco-counties.geojson   (US Census county polygons)
  - site/assets/data/county-search.json      (towns w/ real geocoded coords + URLs,
                                              generated by build.py from COUNTIES
                                              + town_geo.json)
  - build/data/local_spots.json              (her spots; only SOME carry lat/lng)

Writes:
  - mapbox/data/spc-counties.geojson
  - mapbox/data/spc-towns.geojson
  - mapbox/data/spc-local-spots.geojson      (ONLY spots with verified coordinates --
      most spots are geocoded at runtime by netlify/functions/local-spots.js and
      their exact coordinates live in the Netlify Blobs cache, not in this repo.
      The preview page fetches those live and offers a "Download GeoJSON" button
      that includes every spot at its exact geocoded position. Baking a guessed
      coordinate into a committed file is exactly what this repo's rules forbid:
      a wrong number pins her personal recommendation onto someone else's building.)
  - mapbox/preview.html                      (template + embedded data)

Run after editing local_spots.json or adding a town:
    python3 build/tools/export_mapbox_data.py
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SITE_DATA = ROOT / "site" / "assets" / "data"
OUT_DIR = ROOT / "mapbox"
OUT_DATA = OUT_DIR / "data"
TEMPLATE = ROOT / "build" / "tools" / "mapbox_preview_template.html"

SITE_ORIGIN = "https://signaturepropertycollection.com"

# The one POI that lives hardcoded in build/assets/js/map.js (POI_MARKERS)
# rather than in local_spots.json -- carried here too so the Mapbox map
# matches the Leaflet map pin for pin. Coordinates and video are copied
# verbatim from that file, credit and all (it is the City of Loveland's
# film, not Christine's, and the map says so).
BUILTIN_POIS = [
    {
        "name": "Mariana Butte Golf Course",
        "category": "golf",
        "lat": 40.3990, "lng": -105.1430,
        "city": "Loveland",
        "cityHref": "/communities/larimer/loveland.html",
        "searchCity": "Loveland",
        "blurb": ("A public, city-owned 18-hole course along the Big Thompson River "
                  "with sweeping Front Range views — one of the lifestyle perks of "
                  "calling Loveland home."),
        "videoId": "gvO0ZPJ4gD0",
        "videoTitle": "Mariana Butte Golf Course — Loveland, CO",
        "videoSource": "Golf Loveland (City of Loveland)",
    },
]


def load_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def write_json(path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"wrote {path.relative_to(ROOT)}")


def counties_geojson(county_search):
    """Slim the Census polygons to what a Mapbox style needs: the name, the
    site slug, and whether live search covers it. The Census metadata
    (GEO_ID, CENSUSAREA, ...) is dropped -- it bloats the tileset and no
    layer reads it."""
    src = load_json(SITE_DATA / "noco-counties.geojson")
    counties = county_search.get("counties", {})
    feats = []
    for f in src.get("features", []):
        name = (f.get("properties") or {}).get("NAME", "")
        c = counties.get(name, {})
        feats.append({
            "type": "Feature",
            "properties": {
                "name": name,
                "slug": c.get("slug", ""),
                "liveSearch": bool(c.get("liveSearch")),
                "guideUrl": f"{SITE_ORIGIN}/communities/{c.get('slug')}.html" if c.get("slug") else "",
            },
            "geometry": f.get("geometry"),
        })
    return {"type": "FeatureCollection", "features": feats}


def towns_geojson(county_search):
    feats = []
    for cname, c in county_search.get("counties", {}).items():
        for t in c.get("towns", []) or []:
            if not isinstance(t.get("lat"), (int, float)):
                continue
            feats.append({
                "type": "Feature",
                "properties": {
                    "name": t["name"],
                    "county": cname,
                    "pageUrl": SITE_ORIGIN + t.get("url", ""),
                },
                "geometry": {"type": "Point", "coordinates": [t["lng"], t["lat"]]},
            })
    feats.sort(key=lambda f: f["properties"]["name"])
    return {"type": "FeatureCollection", "features": feats}


def spot_properties(s):
    """Public fields only -- the _why bookkeeping keys stay in the repo."""
    keep = ("name", "category", "city", "blurb", "videoId", "videoTitle",
            "videoSource", "views", "reviewViews", "reviewQuote", "reviewDate",
            "googleReviewUrl", "searchCity")
    props = {k: s[k] for k in keep if s.get(k) not in (None, "")}
    if s.get("cityHref"):
        props["pageUrl"] = SITE_ORIGIN + s["cityHref"]
    return props


def spots_geojson(spots):
    feats = []
    skipped = []
    for s in spots:
        if isinstance(s.get("lat"), (int, float)) and isinstance(s.get("lng"), (int, float)):
            props = spot_properties(s)
            props["locationPrecision"] = "exact"
            feats.append({
                "type": "Feature",
                "properties": props,
                "geometry": {"type": "Point", "coordinates": [s["lng"], s["lat"]]},
            })
        else:
            skipped.append(s.get("name", "?"))
    fc = {"type": "FeatureCollection", "features": feats}
    return fc, skipped


def preview_data(county_search, spots):
    """Everything the preview page embeds. Town centers double as the
    approximate fallback position for spots whose exact geocode has to come
    from the live site."""
    towns = []
    for cname, c in county_search.get("counties", {}).items():
        for t in c.get("towns", []) or []:
            if isinstance(t.get("lat"), (int, float)):
                towns.append({
                    "name": t["name"], "county": cname,
                    "lat": t["lat"], "lng": t["lng"],
                    "url": SITE_ORIGIN + t.get("url", ""),
                })
    clean_spots = []
    for s in spots:
        cs = {k: v for k, v in s.items() if not k.startswith("_")}
        clean_spots.append(cs)
    return {
        "siteOrigin": SITE_ORIGIN,
        "counties": counties_geojson(county_search),
        "towns": towns,
        "spots": clean_spots,
    }


def main():
    county_search = load_json(SITE_DATA / "county-search.json")
    local_spots = load_json(ROOT / "build" / "data" / "local_spots.json")
    spots = BUILTIN_POIS + local_spots.get("spots", [])

    write_json(OUT_DATA / "spc-counties.geojson", counties_geojson(county_search))
    write_json(OUT_DATA / "spc-towns.geojson", towns_geojson(county_search))

    spots_fc, skipped = spots_geojson(spots)
    write_json(OUT_DATA / "spc-local-spots.geojson", spots_fc)
    if skipped:
        print(f"  note: {len(skipped)} spots have no verified coordinates in the repo "
              f"and were left out of the committed GeoJSON (their exact pins load "
              f"live in preview.html, which can then download the complete file): "
              + ", ".join(skipped))

    template = TEMPLATE.read_text(encoding="utf-8")
    data_js = json.dumps(preview_data(county_search, spots), ensure_ascii=False,
                         separators=(",", ":"))
    # </script> inside a JSON string would end the script block early.
    data_js = data_js.replace("</", "<\\/")
    assembled, n = re.subn(r"/\*__SPC_DATA_JSON__\*/\s*null", data_js, template, count=1)
    if n != 1:
        raise SystemExit("template placeholder /*__SPC_DATA_JSON__*/null not found")
    out = OUT_DIR / "preview.html"
    out.write_text(assembled, encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(assembled)//1024} KB)")


if __name__ == "__main__":
    main()
