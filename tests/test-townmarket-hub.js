// The town figures can come from the shared data hub -- and only when asked to.
//
// 2026-10-24 (MLS reads through the hub, "nothing lost"). The main site already takes
// these figures from the hub's GET /v1/market/towns (its tests/test-townmarket-hub.js);
// this site's own tool now can too, with `--source hub` or TOWN_STATS_SOURCE=hub (a
// repository variable for .github/workflows/town-market.yml), so both sites show the
// same numbers from the one MLS copy and this workflow no longer needs the Blobs
// secrets. The hub's answer is checked exactly as the main site checks it. Every check
// here runs against a fake of that contract: an injected fetch, and a loopback server on
// 127.0.0.1. Nothing here calls a live API.
//
// What this pins:
//   - unless TOWN_STATS_SOURCE=hub (or --source hub), nothing changes: the Blobs path
//     runs as before and never contacts the hub;
//   - a good answer is written in this file's shape, with a note saying where it came
//     from; EVERY way it can go wrong exits non-zero and leaves the committed file
//     byte-identical (and no temp file behind);
//   - the key is never printed, and neither is the address;
//   - the workflow reaches the hub only when the variable says so, and then needs no
//     Blobs secret.
